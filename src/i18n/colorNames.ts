/**
 * Return the bead color's name in the given locale, falling back to the
 * original English name if the key isn't in the translation table.
 *
 * English locale (or any future locale without an entry) passes through.
 */
export function localizedColorName(englishName: string, locale: Locale): string {
  if (locale === "en") return englishName;
  return T[englishName]?.[locale] ?? englishName;
}

